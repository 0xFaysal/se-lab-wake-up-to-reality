import fs from "node:fs";
import { chromium } from "playwright";
import { open } from "./sess.mjs";
import { newInbox, waitMail } from "./mail.mjs";
import { OUT, BASE, watch } from "./lib.mjs";
const inbox = await newInbox("pe-mgr-");
const acct = { ...inbox, phone: "+88019" + String(Math.floor(10000000 + Math.random() * 89999999)), password: process.env.MANAGER_PASSWORD };
fs.writeFileSync(OUT + "../acct_manager.json", JSON.stringify(acct));
const s = await open("owner"); const p = s.page;
const api = []; p.on("response", async r => { if (r.url().includes("api/v1") && r.request().method() !== "GET") api.push(`${r.request().method()} ${r.status()} ${r.url().replace(/.*api\/v1/,"")} => ${(await r.text().catch(()=>"")).slice(0,160)}`); });
await s.go("/provider/managers/new");
await p.locator("input[name=fullName]").waitFor({ timeout: 60000 });
await p.locator("input[name=fullName]").fill("QA Test Manager");
await p.locator("input[name=email]").fill(inbox.address);
await p.locator("input[name=phone]").fill(acct.phone);
await p.getByText("Select Property").waitFor({ state: "attached" });
await p.locator("main select").first().selectOption({ label: "QA TEST Parking - please delete" }); await p.waitForTimeout(3000);
await p.getByText("Whole Property scope", { exact: true }).click(); await p.waitForTimeout(800); await p.getByRole("button", { name: /create invitation/i }).click(); await p.waitForTimeout(12000);
console.log("PROVIDER:", p.url(), api.join("\n"));
await s.close();
const m = await waitMail(inbox, (sub) => /manager/i.test(sub), 90000);
console.log("MAIL:", m?.subject);
const link = m?.text.match(/https:\/\/parkease-bd\.vercel\.app\/[^\s"<]+/)?.[0];
console.log("link", link);
const b = await chromium.launch({ channel: "msedge" }); const ctx = await b.newContext({ viewport: { width: 1366, height: 850 } }); const q = await ctx.newPage(); const log = watch(q);
await q.goto(link, { waitUntil: "load" }); await q.waitForTimeout(4000);
const pw = q.locator("input[type=password]"); for (let i = 0; i < await pw.count(); i++) await pw.nth(i).fill(acct.password);
await q.getByRole("button", { name: /set|reset|save|continue|update|create/i }).first().click(); await q.waitForTimeout(8000);
await q.goto(BASE + "/login", { waitUntil: "load" }); await q.waitForTimeout(2000);
await q.locator("input").first().fill(acct.address); await q.locator("input[type=password]").fill(acct.password);
await q.getByRole("button", { name: /^sign in$/i }).click(); await q.waitForTimeout(10000);
console.log("MANAGER landed:", q.url()); console.log((await q.locator("body").innerText()).slice(0, 800).replace(/\n+/g, " | "));
await ctx.storageState({ path: OUT + "../state_manager.json" });
await b.close();
